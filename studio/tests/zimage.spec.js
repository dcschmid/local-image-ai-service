import { test, expect } from '@playwright/test';

test('Z-Image variants expose their recipes, literal text and distilled controls', async ({ page }) => {
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const catalog=await(await page.request.get('/studio/api/catalog')).json();
 expect(catalog.models.map(model=>model.id)).toEqual(expect.arrayContaining(['z-image','z-image-turbo']));
 for(const id of ['z-image','z-image-turbo'])expect(catalog.recipes.filter(recipe=>recipe.model===id)).toHaveLength(5);
 await page.goto('/studio/');
 await page.locator('#model').selectOption('z-image');
 await expect(page.locator('#recipe')).toHaveValue('zimage-fantasy');
 await page.locator('#example').click();
 await page.locator('#recipe-quality').selectOption('standard');
 await expect(page.locator('#recipe-preview')).toContainText('40 steps · CFG 4');
 await page.locator('#aspect-ratio').selectOption('3:2');
 await expect(page.locator('#format-note')).toContainText('960 × 640');
 await expect(page.locator('#recipe-preview')).toContainText('960x640');
 await page.locator('#recipe-model-filter').selectOption('z-image-turbo');
 await expect(page.locator('.recipe-card')).toHaveCount(5);
 const sample=catalog.examples['zimage-turbo-sign'];
 await page.locator('[data-recipe-id="zimage-turbo-sign"]').getByRole('button',{name:sample?'Use this example':'Use preset',exact:true}).click();
 await expect(page.locator('#model')).toHaveValue('z-image-turbo');
 await expect(page.locator('#visible-text')).toHaveValue('PETAL');
 await page.locator('#visible-text').fill('TEA HOUSE');
 await expect(page.locator('#recipe-preview')).toContainText("'TEA HOUSE'");
 await expect(page.locator('#recipe-preview')).toContainText('8 steps · CFG 1');
 await expect(page.locator('#recipe-quality option[value="detail"]')).toBeDisabled();
 await page.locator('#recipe-quality').selectOption('preview');
 await expect(page.locator('#recipe-preview')).toContainText('8 steps · CFG 1');
 await page.locator('#expertise-expert').click();await page.locator('#workflow').selectOption('free');
 await expect(page.locator('#cfg')).toBeDisabled();await expect(page.locator('#negative')).toBeDisabled();
 await expect(page.locator('#quality option')).toHaveCount(1);
 await page.locator('#model').selectOption('z-image');
 await expect(page.locator('#cfg')).toBeEnabled();await expect(page.locator('#negative')).toBeEnabled();
 await expect(page.locator('#steps')).toHaveValue('40');
 await expect(page.locator('#recipe-quality option[value="detail"]')).toBeEnabled();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
});
